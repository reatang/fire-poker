"""Native desktop release builder. Run `uv run tools/release.py --help`."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import plistlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import zipfile

import yaml

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "windows-amd64": ("windows", "amd64", ("portable", "installer")),
    "windows-arm64": ("windows", "arm64", ("portable", "installer")),
    "darwin-amd64": ("darwin", "amd64", ("zip", "dmg")),
    "darwin-arm64": ("darwin", "arm64", ("zip", "dmg")),
    "linux-amd64": ("linux", "amd64", ("tar", "deb", "rpm")),
    "linux-arm64": ("linux", "arm64", ("tar", "deb", "rpm")),
}


def metadata():
    data = json.loads((ROOT / "build/release.json").read_text(encoding="utf-8"))
    if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", data["version"]):
        raise ValueError("build/release.json version must be a semantic version")
    return data


def wails_version():
    return re.search(r"github.com/wailsapp/wails/v3\s+(v\S+)", (ROOT / "go.mod").read_text())[1]


def host_target():
    system = {"Windows": "windows", "Darwin": "darwin", "Linux": "linux"}[platform.system()]
    arch = {"amd64": "amd64", "x86_64": "amd64", "arm64": "arm64", "aarch64": "arm64"}[platform.machine().lower()]
    return f"{system}-{arch}"


def write(path, text):
    path = ROOT / path
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def sync_metadata():
    m = metadata()
    numeric = m["version"].split("-")[0]
    write("backend/pkg/version/version", "v" + m["version"] + "\n")
    config_path = ROOT / "build/config.yml"
    config = config_path.read_text(encoding="utf-8")
    for key, value in {"companyName": m["maintainer"], "productName": m["productName"],
                       "productIdentifier": m["identifier"], "description": m["description"],
                       "version": m["version"], "comments": m["productName"], "copyright": ""}.items():
        config = re.sub(rf"(?m)^  {key}:.*$", f"  {key}: {json.dumps(value, ensure_ascii=False)}", config)
    write("build/config.yml", config)
    for file in ("frontend/package.json", "frontend/package-lock.json"):
        data = json.loads((ROOT / file).read_text(encoding="utf-8"))
        data.update(name=m["name"], version=m["version"])
        if "packages" in data:
            data["packages"][""].update(name=m["name"], version=m["version"])
        write(file, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    info = {"fixed": {"file_version": numeric}, "info": {"0804": {
        "ProductVersion": m["version"], "CompanyName": m["maintainer"],
        "FileDescription": m["description"], "LegalCopyright": "", "ProductName": m["productName"],
        "Comments": m["productName"], "OriginalFilename": m["name"] + ".exe", "FileVersion": numeric}}}
    write("build/windows/info.json", json.dumps(info, indent=2, ensure_ascii=False) + "\n")
    manifest = (ROOT / "build/windows/wails.exe.manifest").read_text(encoding="utf-8")
    manifest = re.sub(r'(name="FirePoker.Desktop" version=")[^"]+', r'\g<1>' + numeric + ".0", manifest)
    write("build/windows/wails.exe.manifest", manifest)
    definitions = {"INFO_PROJECTNAME": m["name"], "INFO_COMPANYNAME": m["maintainer"],
                   "INFO_PRODUCTNAME": m["productName"], "INFO_PRODUCTVERSION": numeric, "INFO_COPYRIGHT": ""}
    write("build/windows/nsis/brand.nsh", "; Generated by tools/release.py sync\n" +
          "\n".join(f'!define {key} "{value}"' for key, value in definitions.items()) + "\n")
    for file in ("build/darwin/Info.plist", "build/darwin/Info.dev.plist"):
        info = plistlib.loads((ROOT / file).read_bytes(), fmt=plistlib.FMT_XML)
        info.update(CFBundleName=m["productName"], CFBundleDisplayName=m["productName"],
                    CFBundleExecutable=m["name"], CFBundleIdentifier=m["identifier"],
                    CFBundleVersion=numeric, CFBundleShortVersionString=numeric,
                    CFBundleGetInfoString=m["description"], NSHumanReadableCopyright="")
        write(file, plistlib.dumps(info, sort_keys=False).decode())


def run(args, *, cwd=ROOT, env=None):
    args = [str(arg) for arg in args]
    print("+ " + " ".join(args), flush=True)
    subprocess.run(args, cwd=cwd, env=env, check=True)


def require_tool(name):
    found = shutil.which(name)
    if not found and name == "makensis" and os.name == "nt":
        for base in (os.environ.get("ProgramFiles(x86)", ""), os.environ.get("ProgramFiles", "")):
            candidate = Path(base) / "NSIS/makensis.exe"
            if candidate.is_file():
                found = str(candidate)
    if not found:
        raise RuntimeError(f"Missing build tool: {name}. See docs/desktop-packaging.md")
    return found


def doctor(target, formats):
    if target != host_target():
        raise RuntimeError(f"Native builds required: target {target}, host {host_target()}. Use the matching CI runner.")
    for tool in ("go", "npm", "wails3"):
        require_tool(tool)
    installed = subprocess.check_output([require_tool("wails3"), "version"], stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
    if wails_version().removeprefix("v") not in installed:
        raise RuntimeError(f"Wails CLI must match go.mod: go install github.com/wailsapp/wails/v3/cmd/wails3@{wails_version()}")
    cc = os.environ.get("CC") or ("clang" if target.startswith("darwin") else "gcc")
    if not Path(cc).is_file() and not shutil.which(cc):
        raise RuntimeError("CGO requires a C compiler. Set CC to its executable path.")
    if "installer" in formats:
        require_tool("makensis")
    if target.startswith("darwin"):
        for tool in ("codesign", "ditto", "hdiutil", "xcrun"):
            require_tool(tool)
    if target.startswith("linux"):
        require_tool("pkg-config")
        run(["pkg-config", "--exists", "gtk4", "webkitgtk-6.0"])


def selected_formats(target, value):
    allowed = TARGETS[target][2]
    formats = tuple(value.split(",")) if value else allowed
    if not formats or len(set(formats)) != len(formats) or any(f not in allowed for f in formats):
        raise ValueError(f"Formats for {target}: {','.join(allowed)}")
    return formats


def artifact_name(target, kind):
    m = metadata()
    extension = {"portable": "portable.zip", "installer": "installer.exe", "tar": "tar.gz"}.get(kind, kind)
    return f'{m["name"]}-v{m["version"]}-{target}.{extension}'


def checksums(directory):
    lines = []
    for file in sorted(directory.iterdir()):
        if file.is_file() and file.name != "SHA256SUMS.txt":
            with file.open("rb") as stream:
                lines.append(f"{hashlib.file_digest(stream, 'sha256').hexdigest()}  {file.name}\n")
    (directory / "SHA256SUMS.txt").write_text("".join(lines), encoding="utf-8")


def verify(directory):
    expected = {}
    for line in (directory / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines():
        digest, name = line.split("  ", 1)
        if Path(name).name != name or name in expected:
            raise ValueError("Invalid checksum entry")
        expected[name] = digest
    actual = {file.name for file in directory.iterdir() if file.is_file() and file.name != "SHA256SUMS.txt"}
    if actual != set(expected):
        raise ValueError("Package files do not match checksum inventory")
    for name, digest in expected.items():
        with (directory / name).open("rb") as stream:
            if hashlib.file_digest(stream, "sha256").hexdigest() != digest:
                raise ValueError(f"Checksum mismatch: {name}")
    print(f"Verified {len(expected)} release files")


def build(target, formats, skip_frontend):
    doctor(target, formats)
    sync_metadata()
    system, arch, _ = TARGETS[target]
    m = metadata()
    # Unique empty staging prevents accidentally publishing a previous build or user data.
    final_output = ROOT / "release" / ("v" + m["version"]) / target
    if final_output.exists():
        raise RuntimeError(f"Output already exists: {final_output}. Move the previous release before rebuilding.")
    work_root = ROOT / ".release-work"
    work_root.mkdir(exist_ok=True)
    env = os.environ.copy()
    env.update(GOOS=system, GOARCH=arch, CGO_ENABLED="1")
    if system == "darwin":
        env["MACOSX_DEPLOYMENT_TARGET"] = "11.0" if arch == "arm64" else "10.15"
    run([sys.executable, ROOT / "tools/generate-brand-icon.py"])
    if not skip_frontend:
        run([require_tool("npm"), "ci"], cwd=ROOT / "frontend")
        # Bindings describe host-native services; build tags must match Linux GTK4.
        run(["wails3", "generate", "bindings", "-clean=true", "-ts", "-f", "-tags gtk4" if system == "linux" else ""], env=env)
        run([require_tool("npm"), "run", "build"], cwd=ROOT / "frontend")
    elif not (ROOT / "frontend/dist/index.html").is_file():
        raise RuntimeError("--skip-frontend requires an existing frontend production build")
    with tempfile.TemporaryDirectory(prefix=target + "-", dir=work_root) as temp:
        work = Path(temp)
        output = work / "artifacts"
        output.mkdir()
        binary = work / (m["name"] + (".exe" if system == "windows" else ""))
        if system == "windows":
            run(["wails3", "generate", "syso", "-arch", arch, "-icon", "build/windows/icon.ico", "-manifest", "build/windows/wails.exe.manifest", "-info", "build/windows/info.json", "-out", f"wails_windows_{arch}.syso"])
        tags = "production,gtk4" if system == "linux" else "production"
        flags = "-w -s" + (" -H windowsgui" if system == "windows" else "")
        run(["go", "build", "-tags", tags, "-trimpath", "-buildvcs=false", "-ldflags", flags, "-o", binary, "."], env=env)
        if system == "windows":
            package_windows(work, binary, output, target, formats)
        elif system == "darwin":
            package_macos(work, binary, output, target, formats)
        else:
            package_linux(work, binary, output, target, formats, env)
        write_manifest(output, target, formats)
        checksums(output)
        final_output.parent.mkdir(parents=True, exist_ok=True)
        output.rename(final_output)
    print(f"Artifacts: {final_output}")


def package_windows(work, binary, output, target, formats):
    if "portable" in formats:
        with zipfile.ZipFile(output / artifact_name(target, "portable"), "w", zipfile.ZIP_DEFLATED) as archive:
            archive.write(binary, "fire-poker.exe")
            archive.writestr("start-fire-poker.cmd", '@echo off\r\nsetlocal\r\ncd /d "%~dp0"\r\nset "FIRE_POKER_DATA_DIR=%~dp0data"\r\nset "TEMP=%~dp0data\\temp"\r\nset "TMP=%TEMP%"\r\nif not exist "%TEMP%" mkdir "%TEMP%"\r\nstart "" "%~dp0fire-poker.exe"\r\n')
            archive.writestr("README.txt", "Fire Poker\nPortable mode: run start-fire-poker.cmd; settings and chats stay in data/.\nWebView2 Runtime is required.\n" )
    if "installer" in formats:
        run(["wails3", "generate", "webview2bootstrapper", "-dir", ROOT / "build/windows/nsis"])
        installer = output / artifact_name(target, "installer")
        arch_flag = TARGETS[target][1].upper()
        run([require_tool("makensis"), f"-DARG_WAILS_{arch_flag}_BINARY={binary}", f"-DFIRE_POKER_INSTALLER={installer}", "project.nsi"], cwd=ROOT / "build/windows/nsis")


def package_macos(work, binary, output, target, formats):
    m = metadata()
    app = work / (m["productName"] + ".app")
    (app / "Contents/MacOS").mkdir(parents=True)
    (app / "Contents/Resources").mkdir()
    shutil.copy2(binary, app / "Contents/MacOS" / m["name"])
    info = plistlib.loads((ROOT / "build/darwin/Info.plist").read_bytes())
    info["LSMinimumSystemVersion"] = "11.0" if target.endswith("arm64") else "10.15"
    (app / "Contents/Info.plist").write_bytes(plistlib.dumps(info, sort_keys=False))
    shutil.copy2(ROOT / "build/darwin/icons.icns", app / "Contents/Resources/icons.icns")
    identity = os.environ.get("MACOS_SIGN_IDENTITY", "-")
    command = ["codesign", "--force", "--deep", "--sign", identity]
    if identity != "-":
        command += ["--options", "runtime", "--timestamp"]
    run(command + [app])
    run(["codesign", "--verify", "--deep", "--strict", app])
    profile = os.environ.get("MACOS_NOTARY_PROFILE")
    if profile:
        if identity == "-":
            raise RuntimeError("Notarization requires MACOS_SIGN_IDENTITY")
        submitted = work / "notary.zip"
        run(["ditto", "-c", "-k", "--keepParent", app, submitted])
        run(["xcrun", "notarytool", "submit", submitted, "--keychain-profile", profile, "--wait"])
        run(["xcrun", "stapler", "staple", app])
    if "zip" in formats:
        run(["ditto", "-c", "-k", "--keepParent", app, output / artifact_name(target, "zip")])
    if "dmg" in formats:
        image = work / "dmg"
        image.mkdir()
        shutil.copytree(app, image / app.name, symlinks=True)
        (image / "Applications").symlink_to("/Applications")
        run(["hdiutil", "create", "-volname", m["productName"], "-srcfolder", image, "-format", "UDZO", output / artifact_name(target, "dmg")])


def package_linux(work, binary, output, target, formats, env):
    m = metadata()
    desktop = work / "fire-poker.desktop"
    desktop.write_text(f'[Desktop Entry]\nType=Application\nName={m["productName"]}\nComment={m["description"]}\nExec=fire-poker\nIcon=fire-poker\nTerminal=false\nCategories=Utility;\n', encoding="utf-8")
    if "tar" in formats:
        with tarfile.open(output / artifact_name(target, "tar"), "w:gz") as archive:
            for file in (binary, desktop, ROOT / "build/appicon.png"):
                archive.add(file, arcname="fire-poker/" + file.name)
    if "deb" in formats or "rpm" in formats:
        config = yaml.safe_load((ROOT / "build/linux/nfpm/nfpm.yaml").read_text(encoding="utf-8"))
        config.update(name=m["name"], version=m["version"], arch=TARGETS[target][1], maintainer=m["maintainer"], description=m["description"])
        for entry in config["contents"]:
            entry["src"] = str(binary if entry["dst"].endswith("/fire-poker") else desktop if entry["dst"].endswith(".desktop") else ROOT / "frontend/public/brand/fire-poker-128.png")
        config["scripts"] = {key: str(ROOT / value) for key, value in config.get("scripts", {}).items()}
        package_config = work / "nfpm.yaml"
        package_config.write_text(yaml.safe_dump(config, allow_unicode=True), encoding="utf-8")
        for kind in ("deb", "rpm"):
            if kind in formats:
                dest = work / kind
                dest.mkdir()
                run(["wails3", "tool", "package", "-name", m["name"], "-format", kind, "-config", package_config, "-out", dest], env=env)
                candidates = list(dest.glob("*." + kind))
                if len(candidates) != 1:
                    raise RuntimeError(f"Expected one fresh {kind} package, got {candidates}")
                shutil.copy2(candidates[0], output / artifact_name(target, kind))
def write_manifest(output, target, formats):
    for kind in formats:
        artifact = output / artifact_name(target, kind)
        if not artifact.is_file() or artifact.stat().st_size == 0:
            raise RuntimeError(f"Missing or empty package: {artifact.name}")
    data = dict(metadata(), target=target, formats=list(formats), wails=wails_version(),
                go=subprocess.check_output(["go", "version"], text=True).strip(),
                signing=("developer-id" if os.environ.get("MACOS_SIGN_IDENTITY", "-") != "-" else "ad-hoc") if target.startswith("darwin") else "unsigned",
                notarized=bool(target.startswith("darwin") and os.environ.get("MACOS_NOTARY_PROFILE")))
    (output / "manifest.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("sync", "doctor", "plan", "package", "install-cli", "verify"))
    parser.add_argument("--target", choices=TARGETS, default=host_target())
    parser.add_argument("--formats", help="Comma-separated formats; default: all formats for the target")
    parser.add_argument("--skip-frontend", action="store_true", help="Local reuse only; CI always rebuilds")
    parser.add_argument("--tag", help="Require an exact vVERSION match before any build")
    args = parser.parse_args()
    if args.tag and args.tag != "v" + metadata()["version"]:
        raise ValueError("Release tag must match build/release.json version")
    formats = selected_formats(args.target, args.formats)
    if args.command == "install-cli":
        run(["go", "install", "github.com/wailsapp/wails/v3/cmd/wails3@" + wails_version()])
    elif args.command == "sync":
        sync_metadata()
    elif args.command == "plan":
        print(json.dumps({"target": args.target, "version": metadata()["version"], "wails": wails_version(), "artifacts": [artifact_name(args.target, kind) for kind in formats]}, indent=2))
    elif args.command == "doctor":
        doctor(args.target, formats)
    elif args.command == "verify":
        verify(ROOT / "release" / ("v" + metadata()["version"]) / args.target)
    else:
        build(args.target, formats, args.skip_frontend)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"Release failed: {error}", file=sys.stderr)
        sys.exit(1)
